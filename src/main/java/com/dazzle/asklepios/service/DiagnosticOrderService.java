    /**
     * Creates a new {@link DiagnosticOrder}.
     * <p>
     * Defaults applied when fields are not provided:
     * - status defaults to {@link DiagnosticStatus#NEW}
     * - labStatus defaults to {@link DiagnosticStatus#NEW}
     * - radStatus defaults to {@link DiagnosticStatus#NEW}
     * - isUrgent defaults to {@code false}
     * <p>
     * Notes:
     * - saveDraft is expected to be controlled by the caller (UI/controller).
     * - orderNumber is generated by the database (not set here).
     */
    public DiagnosticOrder create(DiagnosticOrderCreateDTO dto) {
        LOG.debug("[DiagnosticOrderService] CREATE payload={}", dto);
        LOG.info("[DiagnosticOrderService] CREATE requested. patientId={} encounterId={} fromFacilityId={} fromDepartmentId={} isUrgent={}",
                dto.patientId(), dto.encounterId(), dto.fromFacilityId(), dto.fromDepartmentId(), dto.isUrgent());
        Patient patient = patientRepository.findById(dto.patientId())
                .orElseThrow(() -> {
                    LOG.warn("[DiagnosticOrderService] CREATE rejected. reason=patient_not_found patientId={}", dto.patientId());
                    return new NotFoundAlertException(
                            "Patient not found with id " + dto.patientId(),
                            "patient",
                            "notfound"
                    );
                });
        PatientEncounter encounter = patientEncounterRepository.findById(dto.encounterId())
                .orElseThrow(() -> {
                    LOG.warn("[DiagnosticOrderService] CREATE rejected. reason=encounter_not_found encounterId={}", dto.encounterId());
                    return new NotFoundAlertException(
                            "PatientEncounter not found with id " + dto.encounterId(),
                            "patientEncounter",
                            "notfound"
                    );
                });

        facilityHelper.validateFacilityExists(dto.fromFacilityId());
        departmentHelper.validateDepartmentExists(dto.fromDepartmentId());
        DiagnosticOrder order = new DiagnosticOrder();

        order.setEncounterId(encounter.getId());
        order.setPatientId(patient.getId());
        order.setFromDepartmentId(dto.fromDepartmentId());
        order.setFromFacilityId(dto.fromFacilityId());

        DiagnosticStatus labStatus = dto.labStatus() != null ? dto.labStatus() : DiagnosticStatus.NEW;
        DiagnosticStatus radStatus = dto.radStatus() != null ? dto.radStatus() : DiagnosticStatus.NEW;

        order.setStatus(DiagnosticStatus.NEW);
        order.setLabStatus(labStatus);
        order.setRadStatus(radStatus);


        order.setSaveDraft(true);
        order.setIsUrgent(dto.isUrgent() != null ? dto.isUrgent() : false);

        DiagnosticOrder saved = diagnosticOrderRepository.save(order);

        LOG.info(
                "[DiagnosticOrderService] CREATE completed. orderId={} status={} saveDraft={} labStatus={} radStatus={} isUrgent={} fromDepartmentId={} fromFacilityId={}",
                saved.getId(), saved.getStatus(), saved.getSaveDraft(),
                saved.getLabStatus(), saved.getRadStatus(), saved.getIsUrgent(),
                saved.getFromDepartmentId(), saved.getFromFacilityId()
        );

        return saved;
    }


    public DiagnosticOrder update(DiagnosticOrder existing, DiagnosticOrderUpdateDTO dto) {
        LOG.debug("[DiagnosticOrderService] UPDATE payload. orderId={} payload={}", existing.getId(), dto);
        LOG.info("[DiagnosticOrderService] UPDATE requested. orderId={} currentIsUrgent={} requestedIsUrgent={}",
                existing.getId(), existing.getIsUrgent(), dto.isUrgent());

        Boolean oldIsUrgent = existing.getIsUrgent();

        if (dto.isUrgent() != null) {
            existing.setIsUrgent(dto.isUrgent());
        }

        DiagnosticOrder saved = diagnosticOrderRepository.save(existing);

        LOG.info(
                "[DiagnosticOrderService] UPDATE completed. orderId={} status={} saveDraft={} oldIsUrgent={} newIsUrgent={}",
                saved.getId(), saved.getStatus(), saved.getSaveDraft(), oldIsUrgent, saved.getIsUrgent()
        );

        return saved;
    }

