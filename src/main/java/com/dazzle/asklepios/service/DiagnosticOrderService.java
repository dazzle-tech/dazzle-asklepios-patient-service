    /**
     * Submits a draft order.
     * <p>
     * Side effects:
     * - Updates order: saveDraft=false, status=SUBMITTED, submittedBy/submittedDate set
     * - Updates tests: bulk updates all tests under this order to SUBMITTED, excluding CANCELLED tests
     */
    @Transactional
    public DiagnosticOrder submit(DiagnosticOrder existing, String submittedBy) {
        LOG.info("[DiagnosticOrderService] SUBMIT requested. orderId={} currentSaveDraft={} currentStatus={} submittedBy={}",
                existing.getId(), existing.getSaveDraft(), existing.getStatus(), submittedBy);

        DiagnosticStatus oldStatus = existing.getStatus();

        existing.setSaveDraft(false);
        existing.setStatus(DiagnosticStatus.SUBMITTED);
        existing.setSubmittedBy(submittedBy);
        existing.setSubmittedDate(Instant.now());

        DiagnosticOrder saved = diagnosticOrderRepository.save(existing);

        int updatedTests = diagnosticOrderTestRepository.bulkUpdateStatusForOrder(
                saved.getId(),
                DiagnosticOrderTestStatus.SUBMITTED
        );

        LOG.info("[DiagnosticOrderService] Status changed. orderId={} oldStatus={} newStatus={} submittedBy={}",
                saved.getId(), oldStatus, saved.getStatus(), submittedBy);
        LOG.info("[DiagnosticOrderService] SUBMIT completed. orderId={} newSaveDraft={} submittedDate={} updatedTests={}",
                saved.getId(), saved.getSaveDraft(), saved.getSubmittedDate(), updatedTests);

        notificationForUrgentDiagnosticOrder(saved);

        return saved;
    }

    @Transactional
    public DiagnosticOrder submit(Long orderId, String submittedBy) {
        DiagnosticOrder order = findById(orderId);
        if (Boolean.FALSE.equals(order.getSaveDraft())) {
            LOG.warn("[DiagnosticOrderService] SUBMIT rejected. orderId={} reason=already_submitted currentStatus={} saveDraft={}",
                    orderId, order.getStatus(), order.getSaveDraft());
            throw new BadRequestAlertException(
                    "already_submitted",
                    "diagnostic_orders",
                    "Order already submitted"
            );
        }
        return submit(order, submittedBy);
    }

